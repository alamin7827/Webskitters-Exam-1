let x = 10;
let y = 30;

let operator = '/';

switch (operator) {
    case '+': console.log(x+y);
        break;
    case '-': console.log(x-y);
        break;
    case '*': console.log(x*y);
        break;
    case '/': console.log(x/y);
        break;
    default:console.log("Invalid input Please input (+,-,/,*)");

}
